"""Routing writers, one per harness. A writer RENDERS files; it never writes them (route.py does, after approval)."""

from collections.abc import Callable, Mapping
from dataclasses import dataclass
from datetime import date
from pathlib import Path

from yardmaster import __version__
from yardmaster.emit import md_escape, yaml_str
from yardmaster.resolve import ResolvedGroup
from yardmaster.safe_io import read_text
from yardmaster.schema import Plan


@dataclass
class FileChange:
    path: Path
    root: Path  # the directory the write is contained in (project root or the harness config dir)
    old: str | None  # current text, None if the file does not exist yet
    new: str


Writer = Callable[[Plan, list[ResolvedGroup], Path, bool, Mapping[str, str]], list[FileChange]]
WRITERS: dict[str, Writer] = {}


def today() -> str:
    return date.today().isoformat()


def header(prefix: str = "#") -> str:
    return f"{prefix} Generated by Yardmaster {__version__} on {today()}. Edit freely; re-running shows a diff first."


def block_note() -> str:
    return (f"Managed by Yardmaster {__version__} ({today()}). Edits inside this block are replaced the next time it runs; "
            "edit outside it freely.")


def lead(when: str) -> str:
    """`when` as the tail of a sentence: lowercase the first word unless it looks like an acronym or name."""
    w = sentence(when)
    return w[0].lower() + w[1:] if w[1:2].islower() else w


def home(env: Mapping[str, str]) -> Path:
    return Path(env.get("HOME") or env.get("USERPROFILE") or Path.home())


def read_old(path: Path) -> str | None:
    """Current text of a target, or None if absent. Symlinks and unreadable files raise (route reports it)."""
    if not path.exists() and not path.is_symlink():
        return None
    return read_text(path)


def frontmatter(**fields: str) -> str:
    return "---\n" + "".join(f"{k}: {yaml_str(v)}\n" for k, v in fields.items()) + "---\n"


def sentence(when: str) -> str:
    return md_escape(when.strip().rstrip("."))


def examples_text(g: ResolvedGroup) -> str:
    return f" Examples: {', '.join(md_escape(e) for e in g.examples)}." if g.examples else ""


