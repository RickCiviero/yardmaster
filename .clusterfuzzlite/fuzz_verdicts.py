"""ClusterFuzzLite target: bytes given to the verdict and plan validators may only ever raise ValidationError.

build.sh puts the shipped runtime and the shipped pricing.json (as pricing_data.DATA) on PYTHONPATH, so the bundled target
runs the code that ships, not a stub."""

import json
import sys
import tempfile
from pathlib import Path

import atheris
from pricing_data import DATA  # generated by build.sh from skills/yardmaster/pricing.json
from yardmaster.pricing import load_pricing
from yardmaster.schema import ValidationError, validate_plan, validate_verdicts

_DIR = Path(tempfile.mkdtemp())
(_DIR / "pricing.json").write_text(json.dumps(DATA), encoding="utf-8")
PRICING = load_pricing(_DIR / "pricing.json")


def TestOneInput(data: bytes) -> None:
    try:
        doc = json.loads(data)
    except (UnicodeDecodeError, ValueError, RecursionError):
        return
    for check in (lambda: validate_verdicts(doc, manifest_ids={"claude-code:c1"}, pricing=PRICING),
                  lambda: validate_plan(doc, pricing=PRICING)):
        try:
            check()
        except ValidationError:
            pass


def main() -> None:
    atheris.Setup(sys.argv, TestOneInput)
    atheris.Fuzz()


if __name__ == "__main__":
    main()
