"""ClusterFuzzLite target: bytes given to the verdict and plan validators may only ever raise ValidationError.

build.sh puts the shipped runtime and the shipped model catalog (as catalog_data.DATA) on PYTHONPATH, so the bundled target
runs the code that ships, not a stub."""

import json
import sys
import tempfile
from pathlib import Path

import atheris
from catalog_data import DATA  # generated by build.sh from the packaged models.json
from yardmaster.catalog import load_catalog
from yardmaster.schema import ValidationError, validate_plan, validate_verdicts

_DIR = Path(tempfile.mkdtemp())
(_DIR / "models.json").write_text(json.dumps(DATA), encoding="utf-8")
CATALOG = load_catalog(_DIR / "models.json")


def TestOneInput(data: bytes) -> None:
    try:
        doc = json.loads(data)
    except (UnicodeDecodeError, ValueError, RecursionError):
        return
    for check in (lambda: validate_verdicts(doc, manifest_ids={"claude-code:c1"}, catalog=CATALOG),
                  lambda: validate_plan(doc, catalog=CATALOG)):
        try:
            check()
        except ValidationError:
            pass


def main() -> None:
    atheris.Setup(sys.argv, TestOneInput)
    atheris.Fuzz()


if __name__ == "__main__":
    main()
