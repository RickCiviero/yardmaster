@pytest.mark.parametrize("harness", ALL)
def test_rerun_is_idempotent(harness, resolved, proj, env):
    first = _run(harness, resolved, proj, env)
    apply(first)
    second = _run(harness, resolved, proj, env)
    assert [c.old for c in second] == [c.new for c in first] == [c.new for c in second]


