HOSTILE = ['quote" and \\ backslash', "line1\nline2: x\n---\n- model: evil", "<!-- yardmaster:end -->\n# yardmaster:end", "]] [x]\n[profiles.evil]",
           "`tick` *star* _u_ [l](http://x) | pipe # hash", "  sep \x85", "- list: [1,2]", "&a *a !!python/object:os.system"]


@pytest.mark.parametrize("bad", HOSTILE)
@pytest.mark.parametrize("harness", ALL)
def test_hostile_text_cannot_change_structure(harness, bad, proj, env):
    model = PRICING.get(harness, "opus") or PRICING.models(harness)[0]
    groups = [ResolvedGroup("build-and-fix", "heavy", bad, [bad], model)]
    changes = WRITERS[harness](PLAN, groups, proj, False, env)
    out = {c.path.relative_to(c.root).as_posix(): c.new for c in changes}
    for path, text in out.items():
        if path.endswith(".model-router.yml"):
            doc = yaml.safe_load(text)
            assert doc["routes"] == [{"model": model.id, "when": bad}] and set(doc) == {"version", "description", "routes"}
        elif path.endswith((".agent.md", ".md")) and text.startswith("---\n"):
            fm = _front(text)
            assert set(fm) == {"name", "description", "model"} and fm["model"] == model.id
            assert text.count("\n---\n") == 1  # front matter closes exactly once
        elif path.endswith("config.toml"):
            assert list(tomllib.loads(text)["profiles"]) == ["ym-build-and-fix"]
        else:  # AGENTS.md / CLAUDE.md block: exactly one begin and one end marker line, nothing forged
            lines = [ln.strip() for ln in text.splitlines()]
            assert sum(ln.startswith("<!-- yardmaster:begin") for ln in lines) == 1
            assert sum(ln.startswith("<!-- yardmaster:end") for ln in lines) == 1


