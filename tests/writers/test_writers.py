def test_claude_code_subagents_and_claude_md(resolved, proj, env):
    out = rel(_run("claude-code", resolved, proj, env))
    # no env model: the main session is assumed to be the most expensive group, which gets no subagent
    assert sorted(out) == [".claude/agents/ym-build-and-fix.md", ".claude/agents/ym-quick-questions.md", "CLAUDE.md"]
    fm = _front(out[".claude/agents/ym-quick-questions.md"])
    assert fm == {"name": "ym-quick-questions", "description": "Use for: " + PLAN.groups[2].when, "model": "haiku"}
    assert _front(out[".claude/agents/ym-build-and-fix.md"])["model"] == "opus"
    md = out["CLAUDE.md"]
    assert "ym-build-and-fix" in md and "ym-quick-questions" in md and "ym-deep-planning" not in md.split("main session")[0]
    assert "Handle in the main session" in md and "Planning difficult multi-step work" in md


def test_claude_code_main_session_model_from_env_gets_no_subagent(resolved, proj, env):
    out = rel(_run("claude-code", resolved, proj, env | {"ANTHROPIC_MODEL": "claude-opus-5-5"}))
    assert ".claude/agents/ym-build-and-fix.md" not in out  # the session already runs opus
    assert ".claude/agents/ym-deep-planning.md" in out and _front(out[".claude/agents/ym-deep-planning.md"])["model"] == "claude-fable-5-1"


