ALL = ["vscode-copilot", "copilot-cli", "claude-code", "codex"]


def _run(harness, resolved, proj, env, global_=False, deny=frozenset()):
    return WRITERS[harness](PLAN, resolved(harness, deny), proj, global_, env)


def _front(text: str) -> dict:
    assert text.startswith("---\n")
    return yaml.safe_load(text.split("---\n")[1])


def test_all_v1_writers_registered():
    assert set(ALL) <= set(WRITERS)


# ------------------------------------------------------------------ VS Code router
def test_vscode_owner_example_shape(resolved, proj, env):
    (c,) = _run("vscode-copilot", resolved, proj, env)
    assert isinstance(c, FileChange) and c.old is None and c.root == proj
    assert c.path == proj / ".agents" / "model-router" / "yardmaster.model-router.yml"
    doc = yaml.safe_load(c.new)
    assert set(doc) == {"version", "description", "routes"} and doc["version"] == 1
    assert doc["description"] == PLAN.description
    assert all(set(r) == {"model", "when"} for r in doc["routes"])
    assert [r["model"] for r in doc["routes"]] == ["fable", "opus", "gpt-6-luna"]  # most to least expensive
    assert doc["routes"][1]["when"].startswith("Building or changing code over many steps, such as")
    assert c.new.startswith("# Generated by Yardmaster 1.0.0 on 2026-11-23. Edit freely; re-running shows a diff first.\nversion: 1\n")


def test_vscode_has_no_global_router(resolved, proj, env):
    with pytest.raises(ValueError, match="no global router"):
        _run("vscode-copilot", resolved, proj, env, global_=True)


def test_vscode_existing_unmarked_router_shows_full_replace(resolved, proj, env):
    p = proj / ".agents" / "model-router" / "yardmaster.model-router.yml"
    p.parent.mkdir(parents=True)
    mine = 'version: 1\ndescription: "hand written"\nroutes:\n  - model: opus\n    when: Everything.\n'
    p.write_bytes(mine.encode())
    (c,) = _run("vscode-copilot", resolved, proj, env)
    assert c.old == mine and "hand written" not in c.new and c.new.startswith("# Generated by Yardmaster")


# ------------------------------------------------------------------ Copilot CLI
def test_copilot_cli_agents_and_agents_md(resolved, proj, env):
    out = rel(_run("copilot-cli", resolved, proj, env))
    assert sorted(out) == [".github/agents/ym-build-and-fix.agent.md", ".github/agents/ym-deep-planning.agent.md",
                           ".github/agents/ym-quick-questions.agent.md", "AGENTS.md"]
    fm = _front(out[".github/agents/ym-build-and-fix.agent.md"])
    assert fm == {"name": "ym-build-and-fix", "description": PLAN.groups[1].when, "model": "opus"}
    assert "ym-quick-questions" in out["AGENTS.md"] and "gpt-6-luna" in out["AGENTS.md"]


def test_copilot_cli_global_writes_agents_only_under_copilot_home(resolved, proj, env, tmp_path):
    changes = _run("copilot-cli", resolved, proj, env, global_=True)
    assert {c.root for c in changes} == {Path(env["HOME"]) / ".copilot"}
    assert all(c.path.parent.name == "agents" for c in changes) and len(changes) == 3
    env2 = env | {"COPILOT_HOME": str(tmp_path / "ch")}
    assert {c.root for c in _run("copilot-cli", resolved, proj, env2, global_=True)} == {tmp_path / "ch"}


